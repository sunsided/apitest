//! The lockfile (`apitest.lock.nova`): what each contract is pinned to and
//! which part of it the suites use.
//!
//! The recorded usage is what restricts drift detection to the used surface,
//! so the lockfile is meant to be committed.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{Result, anyhow};
use serde::{Deserialize, Serialize};

use super::{Contract, OpUsage};

/// `apitest.lock.nova`: what each contract is pinned to and which surface the suites use.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Lockfile {
    /// Locked entries keyed by [`Contract::name`].
    #[serde(default)]
    pub contract: BTreeMap<String, LockedContract>,
}

/// The lock entry of one contract.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LockedContract {
    /// Path of the pinned spec, relative to the lockfile's directory when both
    /// exist on disk, otherwise as the contract was given.
    pub spec: String,
    /// `info.version` of the pinned spec.
    pub version: String,
    /// Lowercase hex SHA-256 of the pinned spec file. A different hash means
    /// the contract was re-pinned and the usage record starts over.
    pub sha256: String,
    /// Usage recorded by the suites, one entry per operation, sorted by
    /// [`OpUsage::op`].
    #[serde(default)]
    pub used: Vec<OpUsage>,
}

impl Lockfile {
    /// Reads and parses the lockfile at `path`. Returns `Ok(None)` when the
    /// file does not exist yet.
    ///
    /// # Errors
    ///
    /// Fails when the file exists but cannot be read, or when its content does
    /// not match the lock schema (see [`Lockfile::parse`]).
    pub fn load(path: &Path) -> Result<Option<Lockfile>> {
        match std::fs::read_to_string(path) {
            Ok(s) => Ok(Some(Self::parse(&s, &path.display().to_string())?)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e.into()),
        }
    }

    /// Parses `apitest.lock.nova` source text and validates it against the lock schema.
    /// `what` names the source in error messages.
    ///
    /// # Errors
    ///
    /// Fails when `text` is not valid NOVA or does not match
    /// [`crate::config::LOCK_SCHEMA`]; the message lists every schema issue.
    pub fn parse(text: &str, what: &str) -> Result<Lockfile> {
        crate::config::from_nova(text, crate::config::LOCK_SCHEMA, what)
    }

    /// Writes the lockfile to `path`, with a header comment and the schema
    /// directive, replacing any existing file.
    ///
    /// # Errors
    ///
    /// Fails when the lockfile cannot be encoded as NOVA or the file cannot
    /// be written.
    pub fn save(&self, path: &Path) -> Result<()> {
        let body =
            novafile_serde::to_string(self).map_err(|e| anyhow!("encoding lockfile: {e}"))?;
        std::fs::write(
            path,
            format!(
                "# Generated by apitest. Records the API surface your suites depend on.\n# Commit this file.\n@schema apitest-lock@0.1.0\n\n{body}"
            ),
        )?;
        Ok(())
    }

    /// Merges a contract's recorded usage into the lockfile. `lock_dir` is the
    /// directory the lockfile lives in, which [`LockedContract::spec`] is made
    /// relative to. Usage accumulates across runs until the spec's hash changes.
    pub fn record(&mut self, c: &Contract, lock_dir: &Path) {
        let spec = pathdiff(&c.spec_path, lock_dir);
        let entry = self
            .contract
            .entry(c.name.clone())
            .or_insert_with(|| LockedContract {
                spec: spec.clone(),
                version: c.pinned.version.clone(),
                sha256: c.pinned.sha256.clone(),
                used: vec![],
            });
        if entry.sha256 != c.pinned.sha256 {
            // Re-pinned to a different spec: start the usage record over.
            entry.used.clear();
        }

        entry.spec = spec;
        entry.version.clone_from(&c.pinned.version);
        entry.sha256.clone_from(&c.pinned.sha256);
        merge_usage(&mut entry.used, c.usage());
    }
}

/// Folds `fresh` usage into `used`, unioning the sets of operations already
/// present, and keeps `used` sorted by operation id.
fn merge_usage(used: &mut Vec<OpUsage>, fresh: Vec<OpUsage>) {
    for u in fresh {
        match used.iter_mut().find(|e| e.op == u.op) {
            Some(e) => {
                e.params.extend(u.params);
                e.request_fields.extend(u.request_fields);
                e.statuses.extend(u.statuses);
            }
            None => used.push(u),
        }
    }

    used.sort_by(|a, b| a.op.cmp(&b.op));
}

/// `target` relative to `base` (both canonicalized), using `..` where needed.
/// Falls back to `target` as given when either path cannot be canonicalized,
/// e.g. because it does not exist.
fn pathdiff(target: &Path, base: &Path) -> String {
    let (Ok(t), Ok(b)) = (target.canonicalize(), base.canonicalize()) else {
        return target.display().to_string();
    };

    let tc: Vec<_> = t.components().collect();
    let bc: Vec<_> = b.components().collect();
    let common = tc.iter().zip(&bc).take_while(|(a, b)| a == b).count();
    let mut out = PathBuf::new();
    for _ in common..bc.len() {
        out.push("..");
    }

    for c in &tc[common..] {
        out.push(c);
    }

    out.display().to_string()
}
